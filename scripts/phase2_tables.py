#!/usr/bin/env python3
"""Render docs/results/BENCHMARK_PHASE1_2.md tables from phase2_benchmark.json (+ phase2_repo_acoustic.json)."""
from __future__ import annotations
import json
from pathlib import Path

R = Path("docs/results")
d = json.load(open(R / "phase2_benchmark.json"))
lock = json.load(open(R / "phase1_lock.json"))
rp = R / "phase2_repo_acoustic.json"
repo = json.load(open(rp)) if rp.exists() else None
pc = lambda v: "n/a" if v is None or v != v else f"{100 * v:.1f}"
L = []
w = L.append
w("# Phase 1 + 2 benchmark results (auto-generated by `scripts/phase2_tables.py`)\n")
w(f"Generated {d['generated_utc']}. Held-out test audio hash `{lock['heldout_test_audio_sha256'][:16]}...`, manifest hash `{lock['manifest_sha256'][:16]}...` (see `phase1_lock.json`).\n")
w("All rates in %. Positive class = spoof / scam. FPR = genuine human speech (or benign call) flagged. FNR = spoof (or scam) missed. "
  "Thresholds, Platt calibration and abstention bands come from the dev split only; the test split is scored once.\n")
w("## Acoustic: EER by condition (95% bootstrap CI over clips)\n")
mods = ["gmmA", "gmmB", "lrA", "lrB"]
w("| Condition | " + " | ".join(mods) + " |"); w("|---|" + "---|" * len(mods))
for c in d["acoustic"]["by_condition"]["gmmA"]:
    cells = []
    for m in mods:
        v = d["acoustic"]["by_condition"][m][c]
        cells.append(f"{pc(v['eer'])} [{pc(v['eer_ci95'][0])}, {pc(v['eer_ci95'][1])}]")
    w(f"| {c} | " + " | ".join(cells) + " |")
w("\n`gmmA`/`lrA` trained on clean 16 kHz audio; `gmmB`/`lrB` trained on 8 kHz audio through random *seen* conditions (g711 u-law, AMR-NB 12.2k, Opus-NB 12k, bandlimit, u-law+20 dB noise). Unseen test-only: A-law, AMR-NB 4.75k, Opus-WB, noise 10/0 dB, loss, simulated VoIP/PSTN.\n")
w("## Acoustic operating point (dev EER threshold): FPR / FNR / ECE / abstention, model gmmB\n")
w("| Condition | FPR | FNR | ECE | Abstain | FPR kept | FNR kept |"); w("|---|---|---|---|---|---|---|")
for c, v in d["acoustic"]["by_condition"]["gmmB"].items():
    w(f"| {c} | {pc(v['fpr'])} | {pc(v['fnr'])} | {v['ece']:.2f} | {pc(v['abstain_rate'])} | {pc(v['fpr_retained'])} | {pc(v['fnr_retained'])} |")
w("\n## Acoustic by attack family (gmmB; EER of that attack vs all genuine speech / FNR at threshold)\n")
w("| Attack | Type (ASVspoof README) | Algorithm seen in training | clean EER | clean FNR | g711 EER | g711 FNR |"); w("|---|---|---|---|---|---|---|")
for a, v in d["acoustic"]["by_attack"]["gmmB"]["clean_16k"].items():
    g = d["acoustic"]["by_attack"]["gmmB"]["g711_ulaw"][a]
    w(f"| {a} | {v['type']} | {'yes' if v['algorithm_seen_in_training'] else 'no'} | {pc(v['eer_vs_bonafide'])} | {pc(v['fnr'])} | {pc(g['eer_vs_bonafide'])} | {pc(g['fnr'])} |")
w("\n## Acoustic by speaker (67 held-out speakers, gmmB)\n")
w("| Condition | global FPR | speaker FPR median / p90 / max | speaker FNR median / p90 / max | speakers with FPR > 2x global |"); w("|---|---|---|---|---|")
for c, v in d["acoustic"]["by_speaker"]["gmmB"].items():
    w(f"| {c} | {pc(v['global_fpr'])} | {pc(v['fpr_median'])} / {pc(v['fpr_p90'])} / {pc(v['fpr_max'])} | {pc(v['fnr_median'])} / {pc(v['fnr_p90'])} / {pc(v['fnr_max'])} | {v['speakers_fpr_over_2x_global']} |")
if repo:
    w("\n## Repository acoustic scorer (STRF heuristic + prototype memory), subset\n")
    w(repo["note"] + f". Dev EER {pc(repo['dev_eer'])}%. Latency {repo['latency_s_per_audio_s']:.2f} s compute per 1 s audio on 1 CPU.\n")
    w("| Condition | n | EER | FPR | FNR | ECE | Abstain |"); w("|---|---|---|---|---|---|---|")
    for c, v in repo["by_condition"].items():
        w(f"| {c} | {v['n']} | {pc(v['eer'])} | {pc(v['fpr'])} | {pc(v['fnr'])} | {v['ece']:.2f} | {pc(v['abstain_rate'])} |")
w("\n## Language (BothBosu/scam-dialogue, LLM-generated, English, 800 held-out dialogues)\n")
w("| System | WER | EER | AUC | FPR | FNR | ECE | Abstain |"); w("|---|---|---|---|---|---|---|---|")
for m, vs in d["language"]["by_wer"].items():
    for wv, v in vs.items():
        w(f"| {m} | {wv} | {pc(v['eer'])} | {v['auc']:.3f} | {pc(v['fpr'])} | {pc(v['fnr'])} | {v['ece']:.2f} | {pc(v['abstain_rate'])} |")
lm = d["language"]["meta"]
w(f"\nLatency: repo scorer {lm['repo_ms_per_turn_mean']:.2f} ms/turn mean ({lm['repo_ms_per_turn_p95']:.2f} p95); TF-IDF+LR {lm['tfidf_ms_per_dialogue_mean']:.2f} ms/dialogue.\n")
w("Error rate by dialogue type at WER 0 (scam types: ssn, refund, support, reward = missed; benign: delivery, insurance, telemarketing, wrong = false alarm):\n")
w("| Type | " + " | ".join(d["language"]["by_type"].keys()) + " |"); w("|---|" + "---|" * len(d["language"]["by_type"]))
types = list(d["language"]["by_type"]["repo"]["0.0"].keys())
for t in types:
    w(f"| {t} | " + " | ".join(pc(d["language"]["by_type"][m]["0.0"][t]["error_rate"]) for m in d["language"]["by_type"]) + " |")
w("\n## Fusion on paired SYNTHETIC calls (random test clip + random test dialogue; text at WER 0.15; threat = spoof OR scam)\n")
w("Cells show the % flagged: human+benign is the false-positive rate; the other three cells are detection rates.\n")
w("| Condition | System | FPR | FNR | human+benign | human+scam | synthetic+benign | synthetic+scam |"); w("|---|---|---|---|---|---|---|---|")
for c, vs in d["fusion_synthetic_pairs"].items():
    for n, v in vs.items():
        cs = v["rate_flagged_by_cell"]
        w(f"| {c} | {n} | {pc(v['fpr'])} | {pc(v['fnr'])} | {pc(cs['human_benign'])} | {pc(cs['human_scamscript'])} | {pc(cs['synthetic_benign'])} | {pc(cs['synthetic_scamscript'])} |")
w("\n## Axes not covered\n")
for a in d["axes_not_covered"]:
    w(f"- {a}")
(R / "BENCHMARK_PHASE1_2.md").write_text("\n".join(L) + "\n")
print("wrote", R / "BENCHMARK_PHASE1_2.md")
