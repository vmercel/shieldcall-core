"""SIPREC listener (TDD v2.0 §4, ADR-010).

SIPREC arrives on two transports at once: SIP signalling over
UDP (the INVITE that opens the recording session, carrying the
metadata) and RTP media over UDP (one port per stream label).
`SiprecSipListener` binds the SIP port and drives the pure
`SiprecSipHandler`; each accepted stream label gets its own
`SiprecRtpListener` on an allocated UDP port, feeding the
recording session's `handle_rtp`. `attach_siprec_listener`
wires frames into a SidecarRuntime session exactly like the
Twilio and Asterisk paths (concatenate frames, `push_audio`
at 8 kHz).

SIP Digest authentication (RFC 3261 §22) is NOT implemented in
this slice, and RTP carries no credential, so the controls are
network-level, not protocol: the SIP listener accepts requests
only from a configured `allowed_srcs` set (the SRC's addresses),
each RTP listener accepts datagrams only from the SRC that sent
the INVITE, and the operator firewalls both ports to the SRC.
Without `allowed_srcs` or a firewall rule, both ports must be
treated as untrusted. This is a property of SIP/RTP, not a gap
this module can close, and it is recorded here and in the ADR.

Unlike Twilio and Asterisk, the operator cannot pre-open the
call: the recording `session_id` is generated by the SRC. The
INVITE is therefore the call-opening act: the listener opens
the runtime call itself (`rt.open_call(session_id)`) when a
valid INVITE arrives, and closes it on BYE. The gate that
replaces the pre-open rule is the `allowed_srcs` allowlist.
"""

from __future__ import annotations

import asyncio
import logging
import time
from typing import Callable, Dict, List, Optional, Set, Tuple

import numpy as np

from ..ingest.siprec import (
    SiprecError,
    SiprecRecordingSession,
    SiprecSipHandler,
)
from ..ingest.frame import MediaFrame
from ..runtime.runtime import SidecarRuntime

log = logging.getLogger(__name__)

FrameSink = Callable[[str, List[MediaFrame]], None]
"""Called with (call_id, frames) for every batch of frames the
adapter produces. Runs in the event loop; keep it fast."""

DEFAULT_SIP_PORT = 5060
"""The SIP port SIPREC SRCs expect (RFC 3261)."""


class SiprecRtpListener(asyncio.DatagramProtocol):
    """One UDP listener for one SIPREC media stream (one label).

    - session: the recording session the label belongs to.
    - label: the SDP/metadata label of this stream.
    - host/port: the UDP socket to bind.
    - on_frames: sink for decoded frames.
    - allowed_peer: if set, only datagrams from this (host, port)
      are accepted; anything else is dropped and counted. Set to
      the SRC's address (the address its INVITE arrived from).
    """

    def __init__(
        self,
        session: SiprecRecordingSession,
        label: str,
        host: str = "0.0.0.0",
        port: int = 0,
        on_frames: Optional[FrameSink] = None,
        allowed_peer: Optional[Tuple[str, int]] = None,
    ):
        self.session = session
        self.label = label
        self.host = host
        self.port = port
        self.on_frames = on_frames
        self.allowed_peer = allowed_peer
        self.transport: Optional[asyncio.DatagramTransport] = None
        self.error: Optional[SiprecError] = None
        self._dropped_wrong_peer = 0

    async def start(self) -> "SiprecRtpListener":
        """Bind the UDP socket. Raises if already started."""
        if self.transport is not None:
            raise RuntimeError("SiprecRtpListener already started")
        loop = asyncio.get_running_loop()
        transport, _ = await loop.create_datagram_endpoint(
            lambda: self, local_addr=(self.host, self.port)
        )
        self.transport = transport
        sockname = transport.get_extra_info("sockname")
        log.info(
            "siprec RTP listener bound for call %s label %s on %s",
            self.session.call_id,
            self.label,
            sockname,
        )
        return self

    def stop(self) -> None:
        """Close the UDP socket. Idempotent."""
        if self.transport is not None:
            self.transport.close()
            self.transport = None

    @property
    def is_running(self) -> bool:
        return self.transport is not None and not self.transport.is_closing()

    @property
    def bound_port(self) -> Optional[int]:
        if self.transport is None:
            return None
        sockname = self.transport.get_extra_info("sockname")
        return sockname[1] if sockname else None

    def stats(self) -> Dict[str, int]:
        stats = self.session.stats()
        stats["dropped_wrong_peer"] = self._dropped_wrong_peer
        return stats

    def connection_made(self, transport: asyncio.BaseTransport) -> None:
        self.transport = transport  # type: ignore[assignment]

    def datagram_received(self, data: bytes, addr: Tuple[str, int]) -> None:
        if self.error is not None:
            return
        if self.allowed_peer is not None and addr != self.allowed_peer:
            self._dropped_wrong_peer += 1
            return
        try:
            frames = self.session.handle_rtp(self.label, data)
        except SiprecError as exc:
            # Fail closed, like the Asterisk listener: a protocol
            # violation ends the stream rather than being guessed
            # past. The socket is closed so no further audio from
            # this flow is accepted.
            self.error = exc
            log.warning(
                "siprec stream for call %s label %s stopped on protocol error: %s",
                self.session.call_id,
                self.label,
                exc,
            )
            self.stop()
            return
        if frames and self.on_frames is not None:
            self.on_frames(self.session.call_id, frames)

    def error_received(self, exc: Exception) -> None:
        log.warning(
            "siprec RTP listener for call %s label %s socket error: %s",
            self.session.call_id,
            self.label,
            exc,
        )

    def connection_lost(self, exc: Optional[Exception]) -> None:
        self.transport = None


class SiprecSipListener(asyncio.DatagramProtocol):
    """One UDP listener for SIPREC signalling (the SRS side).

    - scored_aor: the AOR of the participant whose voice is
      scored, passed to every recording session.
    - advertise_host: the IP address advertised in SDP answers
      and the Contact header. Must be reachable by the SRC.
    - host/sip_port: the UDP socket to bind for SIP.
    - rtp_port_range: (first, last) UDP ports allocated to media
      streams, one per accepted audio m-line.
    - allowed_srcs: if set, only SIP requests from these IP
      addresses are accepted; anything else is dropped and
      counted. Set it to the SRC's addresses whenever they are
      known. SIP Digest authentication is not implemented in
      this slice, so this allowlist is the gate.
    - on_frames: sink for decoded frames from every stream.
    - on_session_started / on_session_ended: called with the
      recording session when an INVITE creates it / a BYE ends
      it. The serving layer opens and closes the runtime call
      here.
    """

    def __init__(
        self,
        scored_aor: str,
        advertise_host: str,
        host: str = "0.0.0.0",
        sip_port: int = DEFAULT_SIP_PORT,
        rtp_port_range: Tuple[int, int] = (20000, 21000),
        allowed_srcs: Optional[Set[str]] = None,
        on_frames: Optional[FrameSink] = None,
        on_session_started: Optional[Callable[[SiprecRecordingSession], None]] = None,
        on_session_ended: Optional[Callable[[SiprecRecordingSession], None]] = None,
    ):
        self.scored_aor = scored_aor
        self.advertise_host = advertise_host
        self.host = host
        self.sip_port = sip_port
        self.rtp_port_range = rtp_port_range
        self.allowed_srcs = allowed_srcs
        self.on_frames = on_frames
        self._next_rtp_port = rtp_port_range[0]
        self._rtp_listeners: Dict[str, SiprecRtpListener] = {}
        """label -> listener, keyed by label (labels are unique
        per recording session; one session per listener)."""
        self._sessions: Dict[str, SiprecRecordingSession] = {}
        self.transport: Optional[asyncio.DatagramTransport] = None
        self._dropped_wrong_src = 0
        self._user_on_started = on_session_started
        self._user_on_ended = on_session_ended
        self.handler = SiprecSipHandler(
            host=advertise_host,
            sip_port=sip_port,
            scored_aor=scored_aor,
            port_allocator=self._alloc_rtp_port,
            on_session_started=self._session_started,
            on_session_ended=self._session_ended,
        )

    # -- lifecycle ------------------------------------------------------

    async def start(self) -> "SiprecSipListener":
        """Bind the SIP UDP socket. Raises if already started."""
        if self.transport is not None:
            raise RuntimeError("SiprecSipListener already started")
        loop = asyncio.get_running_loop()
        transport, _ = await loop.create_datagram_endpoint(
            lambda: self, local_addr=(self.host, self.sip_port)
        )
        self.transport = transport
        sockname = transport.get_extra_info("sockname")
        log.info("siprec SIP listener bound on %s", sockname)
        return self

    def stop(self) -> None:
        """Close the SIP socket and every RTP listener.
        Idempotent."""
        for listener in list(self._rtp_listeners.values()):
            listener.stop()
        self._rtp_listeners.clear()
        if self.transport is not None:
            self.transport.close()
            self.transport = None

    @property
    def is_running(self) -> bool:
        return self.transport is not None and not self.transport.is_closing()

    @property
    def bound_port(self) -> Optional[int]:
        if self.transport is None:
            return None
        sockname = self.transport.get_extra_info("sockname")
        return sockname[1] if sockname else None

    def stats(self) -> Dict[str, int]:
        return {
            "sessions": len(self._sessions),
            "rtp_listeners": len(self._rtp_listeners),
            "dropped_wrong_src": self._dropped_wrong_src,
        }

    # -- handler callbacks ----------------------------------------------

    def _alloc_rtp_port(self) -> int:
        first, last = self.rtp_port_range
        if self._next_rtp_port > last:
            raise SiprecError(
                f"RTP port range {first}-{last} exhausted"
            )
        port = self._next_rtp_port
        self._next_rtp_port += 1
        return port

    def _session_started(self, session: SiprecRecordingSession) -> None:
        self._sessions[session.call_id] = session
        if self._user_on_started is not None:
            self._user_on_started(session)
        loop = asyncio.get_running_loop()
        loop.create_task(self._start_media(session))

    def _session_ended(self, session: SiprecRecordingSession) -> None:
        self._sessions.pop(session.call_id, None)
        for label in list(session.rtp_ports):
            listener = self._rtp_listeners.pop(label, None)
            if listener is not None:
                listener.stop()
        if self._user_on_ended is not None:
            self._user_on_ended(session)

    async def _start_media(self, session: SiprecRecordingSession) -> None:
        """Bind one RTP listener per accepted stream label."""
        for label, port in session.rtp_ports.items():
            src_host, src_port = session.src_media_addr.get(label, ("", 0))
            # The SRC sends RTP from its offered address under
            # symmetric RTP; fall back to the SIP source address
            # when the offer carried no usable connection line.
            peer = None
            if src_host and src_port:
                peer = (src_host, src_port)
            elif session.remote_addr and src_port:
                peer = (session.remote_addr, src_port)
            listener = SiprecRtpListener(
                session,
                label,
                host=self.host,
                port=port,
                on_frames=self.on_frames,
                allowed_peer=peer,
            )
            try:
                await listener.start()
            except OSError as exc:
                log.warning(
                    "siprec RTP listener for call %s label %s failed to bind "
                    "port %s: %s",
                    session.call_id,
                    label,
                    port,
                    exc,
                )
                continue
            self._rtp_listeners[label] = listener

    # -- DatagramProtocol ----------------------------------------------

    def connection_made(self, transport: asyncio.BaseTransport) -> None:
        self.transport = transport  # type: ignore[assignment]

    def datagram_received(self, data: bytes, addr: Tuple[str, int]) -> None:
        if self.allowed_srcs is not None and addr[0] not in self.allowed_srcs:
            self._dropped_wrong_src += 1
            return
        try:
            response = self.handler.handle_request(data, addr[0])
        except Exception as exc:  # never crash the socket on a bad message
            log.warning("siprec SIP handler error from %s: %s", addr, exc)
            return
        if response is not None and self.transport is not None:
            self.transport.sendto(response.encode(), addr)

    def error_received(self, exc: Exception) -> None:
        log.warning("siprec SIP listener socket error: %s", exc)

    def connection_lost(self, exc: Optional[Exception]) -> None:
        self.transport = None


async def attach_siprec_listener(
    rt: SidecarRuntime,
    scored_aor: str,
    advertise_host: str,
    host: str = "0.0.0.0",
    sip_port: int = DEFAULT_SIP_PORT,
    rtp_port_range: Tuple[int, int] = (20000, 21000),
    allowed_srcs: Optional[Set[str]] = None,
) -> SiprecSipListener:
    """Start a SIPREC listener feeding the runtime.

    The INVITE opens the runtime call (the recording session_id
    becomes the call id); BYE closes it. Frames are concatenated
    and pushed into the session's pipeline at 8 kHz. Returns the
    started listener; the caller owns stopping it.
    """
    def _push(call_id: str, frames: List[MediaFrame]) -> None:
        live = rt.get_call(call_id)
        if live is None:
            return
        samples = np.concatenate([f.samples for f in frames])
        t0 = time.perf_counter()
        live.push_audio(samples, 8000)
        rt.observe_frame_ms((time.perf_counter() - t0) * 1000.0)

    def _started(session: SiprecRecordingSession) -> None:
        rt.open_call(session.call_id)

    def _ended(session: SiprecRecordingSession) -> None:
        rt.close_call(session.call_id)

    listener = SiprecSipListener(
        scored_aor=scored_aor,
        advertise_host=advertise_host,
        host=host,
        sip_port=sip_port,
        rtp_port_range=rtp_port_range,
        allowed_srcs=allowed_srcs,
        on_frames=_push,
        on_session_started=_started,
        on_session_ended=_ended,
    )
    await listener.start()
    return listener
